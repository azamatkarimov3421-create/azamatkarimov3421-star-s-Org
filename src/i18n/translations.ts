type LangListener = (lang: AppLanguage) => void;
const listeners = new Set<LangListener>();

export function onLanguageChange(cb: LangListener): () => void {
  listeners.add(cb);
  return () => listeners.delete(cb);
}

let currentLanguage: AppLanguage = (() => {
  try {
    const saved = localStorage.getItem('nur_chess_lang') as AppLanguage;
    if (saved && TRANSLATIONS[saved]) return saved;
  } catch {}
  return 'uz';
})();

export function getAppLanguage(): AppLanguage {
  return currentLanguage;
}

export function setAppLanguage(lang: AppLanguage): void {
  currentLanguage = lang;
  try {
    localStorage.setItem('nur_chess_lang', lang);
  } catch {}
  listeners.forEach((cb) => {
    try {
      cb(lang);
    } catch (e) {
      console.error('Lang listener error:', e);
    }
  });
}

export function t(key: keyof typeof TRANSLATIONS.uz | string, lang?: AppLanguage): string {
  const activeLang = lang || currentLanguage;
  const dict = (TRANSLATIONS[activeLang] || TRANSLATIONS.uz) as Record<string, string>;
  return dict[key] || (TRANSLATIONS.uz as Record<string, string>)[key] || key;
}

export function useTranslation() {
  const [lang, setLang] = useState<AppLanguage>(currentLanguage);

  useEffect(() => {
    return onLanguageChange((newLang) => {
      setLang(newLang);
    });
  }, []);

  const translate = useCallback(
    (key: keyof typeof TRANSLATIONS.uz | string) => {
      const dict = (TRANSLATIONS[lang] || TRANSLATIONS.uz) as Record<string, string>;
      return dict[key] || (TRANSLATIONS.uz as Record<string, string>)[key] || key;
    },
    [lang]
  );

  return {
    t: translate,
    lang,
    setLanguage: setAppLanguage,
  };
}