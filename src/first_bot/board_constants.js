export function coordToStr(fileIdx, rankIdx) {
    return `${FILES[fileIdx]}${rankIdx + 1}`;
}

export function strToCoord(sqStr) {
    const fileChar = sqStr[0].toUpperCase();
    const rankVal = parseInt(sqStr.slice(1), 10);
    return [FILE_TO_IDX[fileChar], rankVal - 1];
}
